// clipboard.* — recortes del usuario como capturas de la reunión.
//
//   El usuario hace un recorte con su herramienta (Cmd+Ctrl+Mayús+4 lo copia
//   al portapapeles) → changeCount nuevo con una imagen → JPEG + dHash en
//   `<outDir>/<unix_ms>-manual.jpg` → evento `clipboard.image`.
//   Solo mira el portapapeles mientras se graba (Rust lo arranca y lo para) y
//   no importa lo que ya estaba antes de empezar. No necesita el permiso de
//   Grabación de pantalla.

import ActaMacProtocol
import AppKit
import CoreGraphics
import Foundation
import ImageIO

// MARK: - Lógica pura

enum ClipboardPolicy {
    /// Tipos de imagen, en orden de preferencia.
    static let imageTypes = ["public.png", "public.tiff", "public.jpeg"]
    /// Convención de nspasteboard.org: contraseñas, contenido temporal o
    /// generado por la app. Nunca se importan.
    static let privateMarkers = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]

    /// Tipo de imagen a leer, o `nil` si no hay que importar nada.
    static func imageType(in types: [String]) -> String? {
        if types.contains(where: privateMarkers.contains) { return nil }
        // Copiar un fichero en Finder trae su icono como TIFF: no es un recorte.
        if types.contains("public.file-url") { return nil }
        return imageTypes.first(where: types.contains)
    }

    static func isNew(changeCount: Int, last: Int) -> Bool { changeCount != last }
}

struct ClipboardImage: Equatable {
    var jpeg: Data
    var width: Int
    var height: Int
    var phash: UInt64

    /// PNG/TIFF/JPEG → JPEG con el ancho ≤ `maxWidth` (nunca se agranda).
    static func decode(_ data: Data, maxWidth: Int) -> ClipboardImage? {
        guard let src = CGImageSourceCreateWithData(data as CFData, nil), CGImageSourceGetCount(src) > 0,
              let props = CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any],
              let w = props[kCGImagePropertyPixelWidth] as? Int, let h = props[kCGImagePropertyPixelHeight] as? Int,
              w > 0, h > 0
        else { return nil }
        let image: CGImage?
        if w > maxWidth, maxWidth > 0 {
            // El tamaño máximo es el del lado largo.
            let longest = w >= h ? maxWidth : Int((Double(maxWidth) * Double(h) / Double(w)).rounded())
            image = CGImageSourceCreateThumbnailAtIndex(src, 0, [
                kCGImageSourceCreateThumbnailFromImageAlways: true,
                kCGImageSourceCreateThumbnailWithTransform: true,
                kCGImageSourceThumbnailMaxPixelSize: longest,
            ] as CFDictionary)
        } else {
            image = CGImageSourceCreateImageAtIndex(src, 0, nil)
        }
        guard let image, let jpeg = Jpeg.encode(image, quality: 0.85), let phash = DHash.hash(image) else { return nil }
        return ClipboardImage(jpeg: jpeg, width: image.width, height: image.height, phash: phash)
    }
}

// MARK: - Servicio

public actor ClipboardService {
    private let output: Output
    private var task: Task<Void, Never>?

    public init(output: Output) { self.output = output }

    public func start(_ a: ClipboardStartArgs) async throws {
        stop()
        try FileManager.default.createDirectory(atPath: a.outDir, withIntermediateDirectories: true)
        // Lo que ya estaba copiado antes de grabar no es de esta reunión.
        let initial = await MainActor.run { NSPasteboard.general.changeCount }
        let output = output
        task = Task.detached(priority: .utility) {
            var last = initial
            while !Task.isCancelled {
                try? await Task.sleep(for: .milliseconds(700))
                guard !Task.isCancelled else { return }
                let (count, data) = await MainActor.run { Self.readImageIfNew(last: last) }
                last = count
                guard let data else { continue }
                await Self.importImage(data, args: a, output: output)
            }
        }
    }

    public func stop() {
        task?.cancel()
        task = nil
    }

    /// `changeCount` actual y, si cambió y hay una imagen importable, sus datos.
    @MainActor
    private static func readImageIfNew(last: Int) -> (Int, Data?) {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard ClipboardPolicy.isNew(changeCount: count, last: last) else { return (count, nil) }
        let types = pb.types?.map(\.rawValue) ?? []
        guard let type = ClipboardPolicy.imageType(in: types) else { return (count, nil) }
        return (count, pb.data(forType: NSPasteboard.PasteboardType(type)))
    }

    private static func importImage(_ data: Data, args a: ClipboardStartArgs, output: Output) async {
        guard let img = ClipboardImage.decode(data, maxWidth: Int(a.maxWidth)) else {
            await output.log("warn", "clipboard: imagen no legible; no se importa")
            return
        }
        let frame = RingFrame(atUnixMs: Clock.unixMs(), jpeg: img.jpeg, phash: img.phash, width: img.width, height: img.height)
        do {
            let ev = try CaptureFiles.write(frame, reason: .manual, dir: a.outDir, keyword: nil)
            await output.emit(.clipboardImage(ev))
            await output.log("info", "clipboard: recorte \(img.width)x\(img.height) importado")
        } catch {
            await output.log("error", "clipboard: no se pudo guardar el recorte: \(error)")
        }
    }
}
